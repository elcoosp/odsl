//! Drizzle ORM schema interchange: bidirectional OSDL ↔ Drizzle (TypeScript).
//!
//! - [`drizzle_to_osdl`] (import, roadmap Phase 3.5): a Drizzle `pgTable` /
//!   `mysqlTable` / `sqliteTable` schema → an OSDL `Ast` (which the CLI then
//!   serializes via the shared `format_ast` formatter).
//! - [`render_drizzle`] (export): an OSDL `Ast` → a Drizzle TypeScript schema.
//!
//! The Drizzle import is intentionally conservative: it covers the common
//! declarative subset (tables, scalars, primary keys, not-null, unique,
//! defaults, foreign-key references, and native enums) and emits a valid
//! schema. Drizzle-specific features that have no OSDL analogue (e.g. composite
//! primary keys via `primaryKey()`, indexes via `index()`, `.$defaultFn()`)
//! are noted but not yet mapped.

#![allow(clippy::result_large_err)]

use osdl_core::ast::{Ast, Field, Model};
use osdl_core::errors::{OsdlError, ParseError};
use osdl_core::formatter::format_ast;
use osdl_core::types::{FieldType, Intent, Reference, ScalarType};

/// Parse a Drizzle TypeScript schema into an OSDL `Ast`.
pub fn parse_drizzle(src: &str) -> Result<Ast, OsdlError> {
    let mut ast = Ast::new();
    let enums = parse_enums(src);

    // Walk the source line by line, capturing table blocks. A table is
    // `export const <name> = <dialect>Table('<sql_name>', { ... });`.
    let lines: Vec<&str> = src.lines().collect();
    let mut i = 0;
    while i < lines.len() {
        let line = lines[i];
        if let Some((name, sql_name, body)) = scan_table(&lines, &mut i, line) {
            let model = build_model(&name, &sql_name, &body, &enums)?;
            ast.add_model(model);
        } else {
            i += 1;
        }
    }

    Ok(ast)
}

/// Convert a Drizzle TypeScript schema document into OSDL source.
pub fn drizzle_to_osdl(src: &str) -> Result<String, OsdlError> {
    let ast = parse_drizzle(src)?;
    Ok(format_ast(&ast))
}

/// Render an OSDL `Ast` as a Drizzle TypeScript schema (Postgres dialect).
pub fn render_drizzle(ast: &Ast) -> String {
    let mut out = String::new();
    out.push_str("// Generated by `osdl convert to-drizzle`. Do not edit by hand.\n");
    out.push_str("// Source of truth: the OSDL schema.\n\n");
    out.push_str("import { pgTable, serial, integer, bigint, text, varchar, boolean, timestamp, date, uuid, real, doublePrecision, json, jsonb, pgEnum } from 'drizzle-orm/pg-core';\n\n");

    for (_, model) in ast.models() {
        let sql_name = model.name.to_lowercase();
        out.push_str(&format!("export const {} = pgTable('{}', {{\n", model.name.to_lowercase(), sql_name));
        for (_, field) in model.fields() {
            out.push_str(&format!("  {}: {},\n", to_snake(&field.name), render_drizzle_column(field)));
        }
        out.push_str("});\n\n");
    }
    out
}

// ---------------------------------------------------------------------------
// Enums
// ---------------------------------------------------------------------------

struct DrizzleEnum {
    name: String,
    values: Vec<String>,
}

fn parse_enums(src: &str) -> Vec<DrizzleEnum> {
    let mut enums = Vec::new();
    let lines: Vec<&str> = src.lines().collect();
    let mut i = 0;
    while i < lines.len() {
        let line = lines[i].trim();
        // export const roleEnum = pgEnum('role', ['admin', 'user']);
        if let Some(rest) = line.strip_prefix("export const ")
            && let Some(idx) = rest.find(" = pgEnum(")
        {
            let name = rest[..idx].trim().to_string();
            let args = &rest[idx + " = pgEnum(".len()..];
            if let Some(arr_start) = args.find('[') {
                let arr = &args[arr_start..];
                if let Some(arr_end) = arr.find(']') {
                    let inner = &arr[1..arr_end];
                    let values: Vec<String> = inner
                        .split(',')
                        .map(|s| s.trim().trim_matches('\'').trim_matches('"').to_string())
                        .filter(|s| !s.is_empty())
                        .collect();
                    enums.push(DrizzleEnum { name, values });
                }
            }
        }
        i += 1;
    }
    enums
}

// ---------------------------------------------------------------------------
// Table scanning
// ---------------------------------------------------------------------------

/// Scan from `lines[*start]`; if that line begins a table declaration, find
/// the matching closing `});` (tracking nested braces so `varchar('x', { ... })`
/// doesn't fool the scanner) and return `(model_name, sql_name, body)`.
fn scan_table(
    lines: &[&str],
    start: &mut usize,
    line: &str,
) -> Option<(String, String, String)> {
    let trimmed = line.trim();
    let rest = trimmed.strip_prefix("export const ")?;
    // <name> = <dialect>Table('<sql>', {
    let eq = rest.find(" = ")?;
    let name = rest[..eq].trim().to_string();
    let after_eq = &rest[eq + 3..];
    let open_paren = after_eq.find('(')?;
    // The dialect prefix before `Table(` (pg/mysql/sqlite).
    let inner = &after_eq[open_paren + 1..];
    // sql name is the first single-quoted string.
    let q1 = inner.find('\'')?;
    let q2 = inner[q1 + 1..].find('\'')?;
    let sql_name = inner[q1 + 1..q1 + 1 + q2].to_string();
    // Body opens at the first `{` on this same line.
    // Global char offset of `{` within the original `line`.
    let line_brace = line.find('{')?;

    let mut depth = 1i32; // we've entered the table body
    let mut body = String::new();
    // Start on the current line, just after the opening brace.
    accumulate(&mut depth, &mut body, &line[line_brace + 1..]);
    let mut j = *start + 1;
    while j < lines.len() {
        accumulate(&mut depth, &mut body, lines[j]);
        if depth == 0 {
            *start = j + 1;
            return Some((name, sql_name, body));
        }
        j += 1;
    }
    // No closing found; advance past the end.
    *start = lines.len();
    None
}

/// Append `line` text to `body` while tracking brace depth inside string
/// literals; stop once the opening brace is balanced (depth hits 0).
fn accumulate(depth: &mut i32, body: &mut String, line: &str) {
    let mut in_str = false;
    let mut esc = false;
    for c in line.chars() {
        if esc {
            esc = false;
            body.push(c);
            continue;
        }
        match c {
            '\\' => {
                esc = true;
                body.push(c);
            }
            '\'' | '"' => {
                in_str = !in_str;
                body.push(c);
            }
            '{' if !in_str => {
                *depth += 1;
                body.push(c);
            }
            '}' if !in_str => {
                *depth -= 1;
                body.push(c);
                if *depth == 0 {
                    return;
                }
            }
            _ => body.push(c),
        }
    }
    body.push('\n');
}

